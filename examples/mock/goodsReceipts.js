const toDate = (/** @type {string} */ text) => (text ? new Date(text.replace(' ', 'T')) : null);

/** Newest first, as the table is read. Draft rows have no number or dates yet. */
export function createGoodsReceipts() {
  return SAMPLE.map(
    ([id, grNumber, materialDoc, status, documentStatus, orderNum, submitted, end]) => ({
      id,
      grNumber: grNumber || null,
      materialDoc: materialDoc || null,
      status,
      documentStatus,
      orderNum,
      submittedDate: toDate(submitted),
      endDate: end === '-' ? null : toDate(end ?? submitted),
    }),
  );
}
